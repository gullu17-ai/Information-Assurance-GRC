"""Semantic palette shared by CSS, dataframe cells, and native Streamlit widgets.
Run python -m services.design_system after editing to regenerate native config.
"""
from pathlib import Path
COLORS = {
    "canvas": "#f5f8f8", "surface": "#ffffff", "surface-soft": "#eef4f4",
    "ink": "#172d3b", "muted": "#526772", "line": "#cbd9dc",
    "accent": "#086b70", "accent-soft": "#e9f3f2", "accent-ink": "#175b59",
    "sidebar": "#102b38", "sidebar-hover": "#1d3e4b", "sidebar-selected": "#1c4b57",
    "sidebar-ink": "#edf3fc", "sidebar-muted": "#bbced7", "sidebar-line": "#637f8b",
    "focus": "#086b70", "focus-inverse": "#72ded1",
    "critical-bg": "#f9e8eb", "critical-ink": "#922e43",
    "warning-bg": "#faeedf", "warning-ink": "#854919",
    "caution-bg": "#fcf4d9", "caution-ink": "#765b16",
    "positive-bg": "#e0f1ec", "positive-ink": "#176653",
    "info-bg": "#e7eef9", "info-ink": "#2a5487",
    "neutral-bg": "#edf1f6", "neutral-ink": "#4d6078",
}
PALETTE = {tone: (COLORS[f"{tone}-bg"], COLORS[f"{tone}-ink"])
           for tone in ("critical", "warning", "caution", "positive", "info", "neutral")}

def css_variables():
    return ":root{" + "".join(f"--pass-{key}:{value};" for key,value in COLORS.items()) + "}"

def native_theme():
    sections = {
        "theme": {"base":"light", "primaryColor":COLORS["accent"],
                  "backgroundColor":COLORS["canvas"], "secondaryBackgroundColor":COLORS["surface"],
                  "textColor":COLORS["ink"], "borderColor":COLORS["line"],
                  "dataframeHeaderBackgroundColor":COLORS["surface-soft"], "font":"sans serif"},
        "theme.sidebar": {"backgroundColor":COLORS["sidebar"], "secondaryBackgroundColor":COLORS["sidebar-hover"],
                          "textColor":COLORS["sidebar-ink"], "borderColor":COLORS["sidebar-line"]}}
    result = "# Generated by python -m services.design_system; edit COLORS there.\n"
    for section, entries in sections.items():
        result += f"\n[{section}]\n"
        result += "".join(f'{k} = "{v}"\n' for k,v in entries.items())
    return result

if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / ".streamlit" / "config.toml"
    target.parent.mkdir(exist_ok=True)
    target.write_text(native_theme(), encoding="utf-8")
